"""Run against site/preview.py with Python Playwright installed."""
from datetime import date, timedelta
import os
from playwright.sync_api import sync_playwright, expect


def verify(browser, width):
    context = browser.new_context(viewport={"width": width, "height": 840}, reduced_motion="reduce")
    page = context.new_page()
    errors = []
    page.on("pageerror", lambda exc: errors.append(str(exc)))
    page.goto(os.environ.get("KINSHORE_TEST_URL", "http://127.0.0.1:8765") + "/site/index.html", wait_until="domcontentloaded")
    expect(page.get_by_role("navigation", name="Main navigation")).to_be_visible()
    hero = page.locator(".hero-image")
    hero.evaluate("(image) => image.decode()")
    expected_image = "kinshore-weekend-terrace-800.webp" if width <= 720 else "kinshore-weekend-terrace.webp"
    assert hero.evaluate("(image) => image.currentSrc").endswith(expected_image)
    assert page.evaluate("document.documentElement.scrollWidth <= innerWidth")
    expect(page.get_by_role("heading", name="Breakfast outside. Sand by noon.")).to_be_visible()
    assert 'kinshore-kb.webp' in page.locator(".header .brand-symbol").evaluate("(node) => getComputedStyle(node).backgroundImage")
    page.get_by_role("link", name="Meet at Pine terrace").click()
    expect(page.locator("#walk-route")).to_be_visible()
    expect(page.locator("#pine-terrace")).to_have_attribute("aria-pressed", "true")
    page.get_by_role("button", name="Hide walk route").click()
    expect(page.locator("#walk-route")).to_be_hidden()
    expect(page.locator(".map-pin")).to_have_count(24)
    page.get_by_role("button", name="Apartments", exact=True).click()
    expect(page.locator(".map-pin:visible")).to_have_count(5)
    building = page.get_by_role("button", name="Building B", exact=True)
    building.click()
    expect(building).to_have_attribute("aria-pressed", "true")
    expect(page.locator("#directions")).to_contain_text("Main pool side")
    page.get_by_role("button", name="Pools & beach", exact=True).click()
    expect(page.locator("#directions")).to_contain_text("shallow area")
    expect(page.locator("#map-note")).to_contain_text("Pool towels at Reception")
    page.get_by_role("button", name="Show Beach gate on map").press("Enter")
    expect(page.get_by_role("button", name="Beach gate", exact=True)).to_have_attribute("aria-pressed", "true")
    expect(building).to_be_hidden()
    page.get_by_role("button", name="Arrival & parking", exact=True).press("Enter")
    expect(page.locator(".map-pin:visible")).to_have_count(4)
    page.get_by_role("button", name="Show Covered parking on map").press("Enter")
    expect(page.locator("#covered-parking")).to_have_attribute("aria-pressed", "true")
    expect(page.locator("#map-note")).to_contain_text("first come, first served")
    page.get_by_role("link", name="Find open parking").click()
    expect(page.locator("#guest-parking")).to_have_attribute("aria-pressed", "true")
    page.get_by_role("button", name="Eat & shop", exact=True).click()
    page.get_by_role("button", name="Show Bay Kitchen on map").click()
    expect(page.locator("#map-note")).to_have_text("18:00–21:00")
    agenda = page.locator("#saturday-agenda")
    expect(agenda.locator("li")).to_have_count(3)
    expect(agenda).to_contain_text("Morning stretch")
    expect(agenda).to_contain_text("15:30–16:15")
    page.locator(".weekend-dining img").evaluate("(image) => image.decode()")
    page.locator("#saturday").get_by_role("link", name="grill pergolas").click()
    expect(page.locator("#grill-pergolas")).to_have_attribute("aria-pressed", "true")
    expect(page.locator("#map-note")).to_contain_text("17:00–21:00")
    page.get_by_role("link", name="Ask at Reception").click()
    expect(page.locator("#reception")).to_have_attribute("aria-pressed", "true")
    card = page.locator(".room-card").filter(has_text="Poolside One Bedroom")
    card.locator("summary").click()
    expect(card.locator("dl")).to_contain_text("Double sofa bed")
    expect(card).to_contain_text("Pool-facing balcony")
    expect(card.locator(".room-kitchen")).to_contain_text("Induction hob")
    card.locator(".room-link").click()
    expect(page.locator("#category")).to_have_value("one")
    page.locator("#guests").select_option("4")
    start = date.today().replace(day=1) + timedelta(days=32)
    start = start.replace(day=2)
    start += timedelta(days=(4 - start.weekday()) % 7 + 7 * (320, 390, 1440).index(width))
    end = start + timedelta(days=2)
    calendar = page.locator("#open-calendar")
    calendar.focus()
    page.keyboard.press("Enter")
    expect(page.locator("#calendar-grid button:focus")).to_be_visible()
    page.keyboard.press("Escape")
    expect(calendar).to_be_focused()
    page.keyboard.press("Enter")
    page.locator("#calendar-next").click()
    page.locator(f'[data-date="{start.isoformat()}"]').focus()
    page.keyboard.press("Enter")
    expect(page.locator(f'[data-date="{(start + timedelta(days=1)).isoformat()}"]')).to_be_focused()
    page.keyboard.press("ArrowRight")
    expect(page.locator(f'[data-date="{end.isoformat()}"]')).to_be_focused()
    page.keyboard.press("Enter")
    expect(page.locator("#mini-cards")).to_contain_text("€270 for 2 nights")
    page.locator('.mini-card summary').press("Enter")
    expect(page.locator(".mini-card .floor-plan")).to_be_visible()
    expect(page.locator(".mini-card .room-kitchen")).to_contain_text("fridge-freezer")
    page.go_back(wait_until="domcontentloaded")
    card.locator(".room-link").click()
    expect(page.locator("#checkin")).to_have_value(start.isoformat())
    expect(page.locator("#guests")).to_have_value("4")
    expect(page.locator("#mini-cards")).to_contain_text("€270 for 2 nights")

    quotes_api = "**/api/guest/quotes/*"
    page.route(quotes_api, lambda route: route.fulfill(status=503))
    page.get_by_role("button", name="See available apartments").click()
    retry = page.get_by_role("button", name="Try availability again")
    expect(retry).to_be_visible()
    page.unroute(quotes_api)
    retry.click()
    expect(page.locator("#mini-cards")).to_contain_text("€270 for 2 nights")
    def lose_receipt(route):
        if route.request.method == "POST":
            result = route.fetch()
            assert result.status == 201
            route.abort()
        else:
            route.continue_()

    stays_api = "**/api/guest/stays/"
    page.route(stays_api, lose_receipt)
    page.locator('[data-request="one"]').click()
    trip = page.get_by_role("dialog", name="Before you send")
    expect(trip.get_by_label("Children under 18")).to_be_focused()
    expect(trip.locator("#trip-children option")).to_have_count(4)
    page.keyboard.press("Escape")
    expect(page.locator('[data-request="one"]')).to_be_focused()
    page.locator('[data-request="one"]').click()
    trip.get_by_label("Children under 18").select_option("2")
    trip.get_by_label("Bringing a pet").check()
    trip.get_by_label("Arriving by car").check()
    trip.get_by_role("button", name="Send demo request").click()
    expect(page.locator("#request-message")).to_contain_text("Delivery uncertain")
    page.unroute(stays_api, lose_receipt)
    page.locator("#refresh-stay").click()
    expect(page.locator("#stay-list article")).to_have_count(1)
    expect(page.locator("#stay-list")).to_contain_text("Awaiting confirmation")
    expect(page.locator(".stay-trip-labels")).to_have_text("2 under 18 · Bringing a pet · Arriving by car")
    receipt = page.locator("#stay-list").inner_text()
    page.reload(wait_until="domcontentloaded")
    expect(page.locator("#stay-list")).to_have_text(receipt, use_inner_text=True)
    page.locator('[data-request="one"]').click()
    expect(trip.get_by_label("Children under 18")).to_have_value("2")
    expect(trip.get_by_label("Bringing a pet")).to_be_checked()
    expect(trip.get_by_label("Arriving by car")).to_be_checked()
    trip.get_by_role("button", name="Send demo request").click()
    expect(page.locator("#request-message")).to_contain_text("received")
    expect(page.locator("#stay-list article")).to_have_count(1)
    page.locator("#budget").select_option("120")
    page.locator("#broaden").click()
    expect(page.locator(".mini-card")).to_have_count(2)
    if os.environ.get("KINSHORE_TEST_PUBLIC") == "1" or os.environ.get("KINSHORE_TEST_STAFF"):
        verify_confirmed_stay(browser, page)
    assert not errors, errors
    assert page.evaluate("document.documentElement.scrollWidth <= innerWidth")
    context.close()


def verify_confirmed_stay(browser, guest):
    reference = guest.get_by_text("Reference ·", exact=False).inner_text().split(" · ", 1)[1]
    base_url = os.environ["KINSHORE_TEST_URL"]
    request_url = f"{base_url}/reception/requests/{reference}/"
    public = os.environ.get("KINSHORE_TEST_PUBLIC") == "1"
    if public:
        with browser.new_context() as other_workspace:
            outsider = other_workspace.new_page()
            outsider.goto(f"{base_url}/reception/")
            expect(outsider.get_by_role("heading", name="Today at reception")).to_be_visible()
            outsider.get_by_label("Request reference").fill(reference)
            outsider.get_by_role("button", name="Search").click()
            expect(outsider.get_by_role("link", name=reference, exact=True)).to_have_count(0)
            assert outsider.goto(request_url).status == 404

    desk = guest.context.new_page() if public else browser.new_page()
    try:
        if public:
            desk.goto(guest.get_by_role("link", name="Open demo reception").evaluate("(link) => link.href"))
            desk.get_by_label("Request reference").fill(reference)
            desk.get_by_role("button", name="Search").click()
            desk.get_by_role("link", name=reference, exact=True).click()
        else:
            desk.goto(request_url)
            desk.get_by_label("Username").fill(os.environ["KINSHORE_TEST_STAFF"])
            desk.get_by_label("Password").fill(os.environ["KINSHORE_TEST_PASSWORD"])
            desk.get_by_role("button", name="Sign in").click()
        expect(desk.get_by_text("Check whether the assigned apartment can accommodate the pet", exact=False)).to_be_visible()
        expect(desk.locator(".details")).to_contain_text("Arriving by car")
        assigned = desk.get_by_label("Available apartment").input_value().split("-")[0]
        desk.get_by_role("button", name="Confirm", exact=True).click()
        expect(desk.get_by_text("Confirmed", exact=True)).to_be_visible()
        saturday = date.fromisoformat(guest.locator("#checkin").input_value()) + timedelta(days=1)
        desk.get_by_role("link", name="Grill pergolas").click()
        desk.get_by_label("Date (UTC)").fill(saturday.isoformat())
        desk.get_by_role("button", name="Show schedule").click()
        reserve = desk.get_by_role("button", name="Reserve table 1 at 17:00–19:00")
        reserve.locator("..").get_by_label("Stay reference").fill(reference)
        reserve.click()
        release = desk.get_by_role("button", name="Release table 1 at 17:00–19:00")
        expect(release).to_be_visible()
        guest.get_by_role("button", name="Refresh my requests").click()
        grill = guest.locator(".stay-walk").filter(has_text="Grill pergolas")
        expect(grill).to_contain_text("17:00–19:00 · Table 1")
        release.click()
        expect(reserve).to_be_visible()
        guest.get_by_role("button", name="Refresh my requests").click()
        expect(grill).to_have_count(0)
    finally:
        desk.close()

    guest.get_by_role("button", name="Refresh my requests").click()
    arrival = guest.locator(".stay-arrival").filter(has_text="Arrival & what's included")
    expect(arrival.get_by_role("link", name="covered parking")).to_be_visible()
    expect(arrival).to_contain_text("pool towel from Reception")
    route = arrival.get_by_role("link", name=f"Find Building {assigned} on the map")
    expect(route).to_have_attribute("href", f"./index.html#building-{assigned.lower()}")
    dropins = guest.locator(".stay-arrival").filter(has_text="Saturday drop-ins")
    dropins.locator("summary").press("Enter")
    expect(dropins).to_contain_text("Morning stretch")
    expect(dropins).to_contain_text("Family court games")
    guest.get_by_role("button", name="Book the walk").click()
    expect(guest.locator(".stay-walk")).to_contain_text("Booked · 1 place")
    guest.get_by_role("button", name="Cancel walk booking").click()
    expect(guest.get_by_role("button", name="Book the walk")).to_be_visible()
    guest.get_by_role("link", name="Grill pergolas", exact=True).click()
    expect(guest.locator("#grill-pergolas")).to_have_attribute("aria-pressed", "true")


if __name__ == "__main__":
    with sync_playwright() as playwright:
        browser = playwright.chromium.launch(executable_path=os.environ.get("KINSHORE_BROWSER"))
        for width in (320, 390, 1440):
            verify(browser, width)
        browser.close()
    print("Guest route passed on mobile and desktop.")
